"""Generate the sign table the hieroglyph layout engine reads.

For every glyph in the bundled Noto Sans Egyptian Hieroglyphs font, writes its Gardiner code
(taken from the Unicode character name, so "EGYPTIAN HIEROGLYPH AA001" becomes "Aa1"), its
codepoint, and its ink box in font units. The quadrat layout needs real proportions: a flat sign
like the water ripple N35 and a tall one like the reed M17 cannot be stacked sensibly without them.

Run after replacing the font:  python -X utf8 tools/gen_signs.py
"""
from __future__ import annotations

import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ttf import Font  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "core-ui", "src", "main", "res", "font", "noto_sans_egyptian_hieroglyphs.ttf")
OUT = os.path.join(ROOT, "core-script", "src", "main", "resources", "com", "krbavcic", "pentalingo",
                   "script", "signs.tsv")

NAME = re.compile(r"^EGYPTIAN HIEROGLYPH ([A-Z]+)(\d+)([A-Z]*)$")


def gardiner(name: str) -> str | None:
    m = NAME.match(name)
    if not m:
        return None
    category, number, suffix = m.groups()
    # Unicode spells the two-letter categories in capitals; Gardiner's own convention is "Aa".
    # The nome categories NL and NU stay as they are.
    if category == "AA":
        category = "Aa"
    return f"{category}{int(number)}{suffix}"


def main() -> None:
    font = Font(FONT)
    rows = []
    for cp in range(0x13000, 0x13430):
        name = unicodedata.name(chr(cp), "")
        code = gardiner(name)
        if code is None or cp not in font.cmap:
            continue
        glyph = font.cmap[cp]
        box = font.glyph_box(glyph)
        if box is None:
            continue
        rows.append((code, cp, box, font.advance(glyph)))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# generated by tools/gen_signs.py from {os.path.basename(FONT)}\n")
        f.write(f"# unitsPerEm={font.units_per_em}\n")
        f.write("# code\tcodepoint\txMin\tyMin\txMax\tyMax\tadvance\n")
        for code, cp, box, adv in rows:
            f.write(f"{code}\t{cp:X}\t{box.x_min}\t{box.y_min}\t{box.x_max}\t{box.y_max}\t{adv}\n")

    heights = sorted(r[2].y_max - r[2].y_min for r in rows)
    print(f"wrote {len(rows)} signs to {os.path.relpath(OUT, ROOT)}")
    print(f"ink heights: min={heights[0]} median={heights[len(heights) // 2]} "
          f"p90={heights[int(len(heights) * 0.9)]} max={heights[-1]} (unitsPerEm={font.units_per_em})")
    for probe in ("A1", "M17", "G17", "N35", "X1", "D21", "Z1", "O1", "S34"):
        r = next(r for r in rows if r[0] == probe)
        b = r[2]
        print(f"  {probe:<4} U+{r[1]:X} w={b.x_max - b.x_min} h={b.y_max - b.y_min} "
              f"y={b.y_min}..{b.y_max} adv={r[3]}")


if __name__ == "__main__":
    main()
